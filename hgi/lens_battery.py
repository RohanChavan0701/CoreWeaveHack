# --- the scorers -------------------------------------------------------------------------------

def _value(v: float | None, reason: str | None = None) -> dict[str, Any]:
    return {"value": v} if v is not None else {"value": None, "unevaluable": reason or "not evaluable"}


class DecoyRejection(weave.Scorer):
    """The floor gate: on a decoy, 1.0 when the lens filed nothing (rejected the plant), 0.0 when it took the bait. Signals are not evaluable here."""

    name: str = "decoy_rejection"

    @weave.op
    def score(self, *, output: dict, is_decoy: bool, **kwargs) -> dict:
        if not is_decoy:
            return _value(None, "not a decoy item")
        return _value(0.0 if output.get("filed") else 1.0)


class SignalCaught(weave.Scorer):
    """The complement: on a genuine signal, 1.0 when the lens filed it, 0.0 when it missed. Decoys are not evaluable here."""

    name: str = "signal_caught"

    @weave.op
    def score(self, *, output: dict, is_decoy: bool, **kwargs) -> dict:
        if is_decoy:
            return _value(None, "not a signal item")
        return _value(1.0 if output.get("filed") else 0.0)


SCORERS = [DecoyRejection, SignalCaught]


# --- the answerer ------------------------------------------------------------------------------

class LensBatteryModel(weave.Model):
    """Answers each battery item with the ``pass`` role, the way the close lenses are walked, and records whether it filed."""

    _outputs: list[dict[str, Any]] = PrivateAttr(default_factory=list)

    @property
    def outputs(self) -> list[dict[str, Any]]:
        return self._outputs

    @weave.op
    def predict(self, item: str, lens: str, lens_spec: dict, subject: dict, is_decoy: bool, kind: str) -> dict[str, Any]:
        payload = roles.request("lens", lens=lens_spec, subject=subject, empty_is_legal=roles.EMPTY_LENS_IS_LEGAL)
        c = _model.complete("pass", payload, records_in_context=[lens])
        out = c.json()
        if not isinstance(out, dict):
            out = {}
        findings = [f for f in out.get("findings", []) if isinstance(f, dict)]
        result = {"item": item, "lens": lens, "is_decoy": is_decoy, "kind": kind,
                  "answer": str(out.get("answer", "")), "findings": findings, "filed": filed_any(findings), "call": c.call}
        self._outputs.append(result)
        return result


class ExaminerControlModel(weave.Model):
    """Attacks each planted draft through the examiner fan, one angle in its own context, and records whether that angle landed."""

    _store: Any = PrivateAttr(default=None)
    _outputs: list[dict[str, Any]] = PrivateAttr(default_factory=list)

    def __init__(self, store: Store, **data: Any):
        super().__init__(**data)
        self._store = store

    @property
    def outputs(self) -> list[dict[str, Any]]:
        return self._outputs

    @weave.op
    def predict(self, item: str, lens: str, draft: dict, evidence: dict, is_decoy: bool, kind: str) -> dict[str, Any]:
        from hgi import consolidate as _consolidate

        store: Store = self._store
        angle = next(l for l in store.registry.lenses("examiner") if l.id == lens)
        record = Consolidation(id=CONTROL, started_at=now(), after_pass=0, sessions_read=[])
        payload, c = _consolidate.attack(store, record, store.parse_as(Draft, draft), evidence, lenses=[angle])
        claims = [x for x in payload["claims"] if x.get("lens") == lens]
        landed = any(x.get("landed") for x in claims)
        result = {"item": item, "lens": lens, "is_decoy": is_decoy, "kind": kind, "claims": claims, "filed": landed, "call": c.call if c else None}
        self._outputs.append(result)
        return result


class CoderControlModel(weave.Model):
    """Codes each planted observation blind and records whether the coder named the term, or escaped."""

    _store: Any = PrivateAttr(default=None)
    _outputs: list[dict[str, Any]] = PrivateAttr(default_factory=list)

    def __init__(self, store: Store, **data: Any):
        super().__init__(**data)
        self._store = store

    @property
    def outputs(self) -> list[dict[str, Any]]:
        return self._outputs

    @weave.op
    def predict(self, item: str, lens: str, name: str, noticed: str, term: str | None, is_decoy: bool, kind: str) -> dict[str, Any]:
        store: Store = self._store
        coded, call = _coder.code([{"name": name, "noticed": noticed}], store.registry.terms("convention"), session=LENS_BATTERY, records_in_context=[])
        terms = coded.get(name, [])
        registered = [t for t in terms if not is_escape(t)]
        escaped = [t for t in terms if is_escape(t)]
        # a signal is caught when the coder returned the planted term; a decoy is rejected when it escaped and named no term
        filed = (term in registered) if term else bool(registered) or not escaped
        result = {"item": item, "lens": lens, "is_decoy": is_decoy, "kind": kind, "terms": terms, "expected": term, "filed": filed, "call": call}
        self._outputs.append(result)
        return result


# --- telemetry and facts -----------------------------------------------------------------------

def _variance(xs: list[float]) -> float:
    if not xs:
        return 0.0
    mean = sum(xs) / len(xs)
    return sum((x - mean) ** 2 for x in xs) / len(xs)


def telemetry_from(outputs: list[dict[str, Any]]) -> dict[str, LensTelemetry]:
    """Per-lens telemetry, computed from the battery run: the decoy-rejection fraction, the signal-caught fraction and the filing variance.

    ``decoy_rejection`` and ``signal_caught`` are the two halves of the same run — the fraction of decoys the lens filed
    nothing for and the fraction of genuine signals it filed — so a lens that rejects every decoy but catches only half
    its signals reads a partial signal-miss on the register the decoy axis alone would hide.
    """
    by_lens: dict[str, list[dict]] = defaultdict(list)
    for o in outputs:
        by_lens[o["lens"]].append(o)
    telemetry = {}
    for lens_id, rows in by_lens.items():
        decoys = [r for r in rows if r["is_decoy"]]
        rejected = [r for r in decoys if not r["filed"]]
        signals = [r for r in rows if not r["is_decoy"]]
        caught = [r for r in signals if r["filed"]]
        variance = _variance([1.0 if r["filed"] else 0.0 for r in rows])
        if decoys:
            fraction = len(rejected) / len(decoys)
            decoy = f"{fraction:.2f} — {len(rejected)}/{len(decoys)} planted decoys rejected ({LENS_BATTERY})"
        else:
            decoy = f"unevaluable — no decoy in the battery ({LENS_BATTERY})"
        if signals:
            fraction = len(caught) / len(signals)
            signal = f"{fraction:.2f} — {len(caught)}/{len(signals)} planted signals caught ({LENS_BATTERY})"
        else:
            signal = f"unevaluable — no signal in the battery ({LENS_BATTERY})"
        spread = ("filings vary across" if variance > 0 else "the same filing on all") + f" {len(rows)} battery items"
        telemetry[lens_id] = LensTelemetry(answer_variance=f"{variance:.2f} — {spread} ({LENS_BATTERY})",
                                           decoy_rejection=decoy, signal_caught=signal)
    return telemetry


def facts_from(summary: dict[str, Any], as_of: datetime, source: str | None) -> dict[str, Fact]:
    """The battery's scorer means as fact series ``lens-battery-v1/<scorer>``; a series no row could evaluate reads unevaluable."""
    facts = {}
    for scorer in SCORERS:
        name = scorer.model_fields["name"].default
        block = summary.get(name) or summary.get(scorer.__name__) or {}
        mean = (block.get("value") or {}).get("mean") if isinstance(block, dict) else None
        series = f"{LENS_BATTERY}/{name}"
        facts[name] = Fact(series=series, value=mean, as_of=as_of, source=source) if mean is not None else \
            Fact(series=series, unevaluable="no row was evaluable on this series", as_of=as_of, source=source)
    return facts


@dataclass
class BatteryResult:
    telemetry: dict[str, LensTelemetry]
    facts: dict[str, Fact]
    run: str | None
    outputs: list[dict[str, Any]] = field(default_factory=list)


# --- the run -----------------------------------------------------------------------------------

def run_battery(store: Store, lenses: list[Any] | None = None) -> BatteryResult:
    """Run the battery over the store's close lenses and return the per-lens telemetry and the scorer facts."""
    tracing.init()
    lenses = lenses if lenses is not None else store.registry.lenses("close")
    rows = dataset_rows(lenses)
    if not rows:
        return BatteryResult(telemetry={}, facts={}, run=None, outputs=[])
    model = LensBatteryModel()
    dataset = weave.Dataset(name=f"{LENS_BATTERY}-{len(rows)}", rows=rows)
    evaluation = Evaluation(name=LENS_BATTERY, dataset=dataset, scorers=[s() for s in SCORERS],
                            evaluation_name=f"{tracing.run_label()}{LENS_BATTERY}")
    with tracing.attributes(role="lens-battery", records_in_context=[l.id for l in lenses]):
        summary, call = asyncio.run(_evaluate(evaluation, model))
    stamp = now()
    uri = tracing.call_uri(call)
    return BatteryResult(telemetry=telemetry_from(model.outputs), facts=facts_from(summary, stamp, uri),
                         run=uri, outputs=model.outputs)


def _run(store: Store, model: Any, rows: list[dict[str, Any]], label: str, records: list[str]) -> BatteryResult:
    """One traced evaluation over planted rows: the battery's scorers, the outputs' telemetry, the scorer facts."""
    if not rows:
        return BatteryResult(telemetry={}, facts={}, run=None, outputs=[])
    dataset = weave.Dataset(name=f"{LENS_BATTERY}-{label}-{len(rows)}", rows=rows)
    evaluation = Evaluation(name=LENS_BATTERY, dataset=dataset, scorers=[s() for s in SCORERS],
                            evaluation_name=f"{tracing.run_label()}{LENS_BATTERY} {label}")
    with tracing.attributes(role="lens-battery", records_in_context=records):
        summary, call = asyncio.run(_evaluate(evaluation, model))
    uri = tracing.call_uri(call)
    return BatteryResult(telemetry=telemetry_from(model.outputs), facts=facts_from(summary, now(), uri), run=uri, outputs=model.outputs)


def run_examiner_control(store: Store, lenses: list[Any] | None = None) -> BatteryResult:
    """The examiner control over the register's examiner-hosted lenses: per lens the telemetry of its landing on the planted
    fault and its non-landing on the plausible draft, each item walked in its own context."""
    tracing.init()
    lenses = lenses if lenses is not None else store.registry.lenses("examiner")
    return _run(store, ExaminerControlModel(store), examiner_rows(store, lenses), "examiner-control", [l.id for l in lenses])


def run_coder_control(store: Store) -> dict[str, Any]:
    """The coder control: the payload ``controls.json`` carries — the coder's telemetry strings, the facts, and every item's coding."""
    tracing.init()
    result = _run(store, CoderControlModel(store), coder_rows(), "coder-control", [])
    t = result.telemetry.get(CODER) or LensTelemetry()
    return {CODER: {"decoy_rejection": t.decoy_rejection, "signal_caught": _fact_cell(result.facts.get("signal_caught")),
                    "answer_variance": t.answer_variance, "run": result.run, "as_of": now().isoformat(),
                    "items": [{"item": o["item"], "kind": o["kind"], "expected": o["expected"], "terms": o["terms"], "filed": o["filed"], "call": o["call"]}
                              for o in result.outputs]}}


def _fact_cell(fact: Fact | None) -> str:
    if fact is None:
        return f"unevaluable — no row was evaluable ({LENS_BATTERY})"
    return f"{fact.value:.2f} ({LENS_BATTERY})" if fact.value is not None else f"unevaluable — {fact.unevaluable} ({LENS_BATTERY})"


def controls_path(store: Store):
    return store.index_dir / "controls.json"


def write_controls(store: Store, payload: dict[str, Any]) -> None:
    """Write the coder control's telemetry beside the projections; :mod:`hgi.index` regenerates every projection and leaves this file alone."""
    _registry.write_json(controls_path(store), payload)


def _miss_stream(steer_ids: list[str]) -> str:
    """The miss stream a lens reads: the steers whose indictment cites it — the misses of that lens a human caught."""
    if not steer_ids:
        return f"no steer cites this lens ({LENS_BATTERY})"
    n = len(steer_ids)
    return f"{n} steer{'' if n == 1 else 's'} cite{'s' if n == 1 else ''} this lens: {', '.join(sorted(steer_ids))}"


def populate_telemetry(store: Store, telemetry: dict[str, LensTelemetry]) -> list[str]:
    """Write the computed telemetry onto the lens register, moving each battered lens off ``design-stage``; returns the ids updated.

    The ``miss_stream`` cell is wired from real data here rather than in :func:`telemetry_from`, which sees only the
    battery outputs: a human steer's indictment can name a lens (:func:`hgi.steers.indictment`), and the stream a lens
    reads is the steers that cite it. The battery axes are the rest of the cell; the miss stream is the store's steers.
    """
    citing: dict[str, list[str]] = defaultdict(list)
    for steer in store.all("steer"):
        if steer.indicts is not None:  # type: ignore[attr-defined]
            citing[steer.indicts.record].append(steer.id)  # type: ignore[attr-defined]
    path = store.registry.path("lenses")
    raw = _registry.read_json(path)
    updated = []
    for item in raw:
        t = telemetry.get(item.get("id"))
        if t is not None:
            item["telemetry"] = {**t.model_dump(), "miss_stream": _miss_stream(citing.get(item["id"], []))}
            updated.append(item["id"])
    _registry.write_json(path, raw)
    return updated


# --- the command --------------------------------------------------------------------------------

def _report(label: str, result: BatteryResult) -> None:
    for lens_id, t in sorted(result.telemetry.items()):
        print(f"{lens_id}: decoy_rejection {t.decoy_rejection}; answer_variance {t.answer_variance}")
    scores = ", ".join(f"{k}={'unevaluable' if f.value is None else f'{f.value:.2f}'}" for k, f in result.facts.items())
    print(f"{LENS_BATTERY} {label}: {scores}" + (f"; run {result.run}" if result.run else "; untraced (no Weave project)"))


def _cmd(args, store_of, finish) -> int:
    store = store_of(args)
    battery = run_battery(store)
    updated = populate_telemetry(store, battery.telemetry)
    _report("close lenses", battery)
    examiner = run_examiner_control(store)
    updated += populate_telemetry(store, examiner.telemetry)
    _report("examiner control", examiner)
    coder = run_coder_control(store)
    write_controls(store, coder)
    print(f"{CODER}: signal_caught {coder[CODER]['signal_caught']}; decoy_rejection {coder[CODER]['decoy_rejection']} → {controls_path(store)}")
    finish(store, args, f"Lens battery: score decoy rejection and populate telemetry for {', '.join(updated) or 'no lens'}; the coder control to index/controls.json")
    return 0


def register(add, store_of, finish) -> None:
    p = add("lens-battery", "run the lens battery and the seeded controls: score decoy rejection, populate lens telemetry, write the coder control")
    p.set_defaults(fn=lambda args: _cmd(args, store_of, finish))
