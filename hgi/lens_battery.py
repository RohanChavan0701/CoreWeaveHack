def control_draft(store: Store, name: str, sketch: dict[str, Any]) -> Draft:
    """A planted draft: the sketch's judgment with the body derived the way every draft's is, never a hand-written mechanism."""
    body = _drafting.body(_drafting.sketch_of(sketch, store.registry), ["O-0001", "O-0002"], store.registry.bars, _model.model_id("pass"))
    return store.parse_as(Draft, {"uid": store.new_uid(), "name": name, "kind": "decision", "drafted_at": now().isoformat(), "proposed_by": LENS_BATTERY,
                                  "rung": "new-decision", "rung_why": "a planted control draft", "body": body, "evidence": ["O-0001", "O-0002"]})


def examiner_items(store: Store, lens_id: str) -> list[dict[str, Any]]:
    """The two plants for an examiner lens: the signal carrying a fault of its class, the decoy carrying none."""
    fault = EXAMINER_FAULTS.get(lens_id)
    if fault is None:
        return []
    decoy = control_draft(store, f"P-control-{lens_id}-decoy", CONTROL_SKETCH)
    signal = control_draft(store, f"P-control-{lens_id}-signal", {**CONTROL_SKETCH, **fault.get("sketch", {})})
    return [{"kind": "decoy", "why": "a plausible draft with no fault of this class", "draft": decoy, "evidence": CONTROL_EVIDENCE},
            {"kind": "signal", "why": fault["why"], "draft": signal, "evidence": {**CONTROL_EVIDENCE, **fault.get("evidence", {})}}]


def examiner_rows(store: Store, lenses: list[Any]) -> list[dict[str, Any]]:
    """One row per plant per examiner lens, the draft and evidence carried whole so predict is self-contained."""
    rows = []
    for lens in lenses:
        for n, item in enumerate(examiner_items(store, lens.id)):
            rows.append({"item": f"{lens.id}/{item['kind']}/{n}", "lens": lens.id, "draft": item["draft"].model_dump(by_alias=True, mode="json"),
                         "evidence": item["evidence"], "is_decoy": item["kind"] == "decoy", "kind": item["kind"]})
    return rows


